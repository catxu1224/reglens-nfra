TRAILING_PERSONS = re.compile(r"\s*(?:及|并)?\s*相关(?:责任)?人员?\s*$")
LEGAL_SUFFIX = re.compile(r"(股份有限公司|有限责任公司|有限公司|集团公司|公司)")
BRANCH_HINT = re.compile(r"(分行|支行|分公司|中心支公司|中心支行|营业部|分理处|信用卡中心|电话销售中心|分中心|办事处)")
