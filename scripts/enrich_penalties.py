def clean(v: str) -> str:
    return re.sub(r"\s+", " ", (v or "")).strip(" ：:，,。；;")


def trim_branch_role(value: str) -> str:
    match = BRANCH_ROLE.search(value)
    return clean(value[:match.start()]) if match else clean(value)


def split_subject(subject: str) -> Tuple[str, str]:
    subject = TRAILING_PERSONS.sub("", clean(subject))
    # 个人责任人常以“姓名（某分行行长）”形式出现，不应将职务中的“分行”当作机构。
    if ("（" in subject or "(" in subject or "[" in subject or "【" in subject) and not LEGAL_SUFFIX.search(subject):
        return subject, ""
    # 多个处罚对象分别处理，避免把“及相关责任人”带入公司名称。
    parts = re.split(r"\s*(?:、|；|;)\s*", subject)
    companies: List[str] = []
    branches: List[str] = []
    for part in parts:
        part = clean(part)
        if not part:
            continue
        match = LEGAL_SUFFIX.search(part)
        if match:
            company = part[: match.end()]
            rest = trim_branch_role(part[match.end():])
            if rest and BRANCH_HINT.search(rest):
                companies.append(company)
                branches.append(rest)
            else:
                # 个人括号中的“某机构总经理/客户经理”等不是机构名称的一部分。
                companies.append(company)
        else:
            # 无法人后缀时，保留原文，只有明确分支词才拆分。
            bmatch = BRANCH_HINT.search(part)
            if bmatch and bmatch.start() > 0:
                prefix = part[: bmatch.start()]
                # “广发银行平顶山分行”“中国农业发展银行云南省分行”等名称
                # 没有“有限公司”后缀，需把机构名称和地区分支一起识别。
                bank = re.match(r"^(.*?(?:银行|保险|证券|信托|财务公司|金融公司|农行|工行|建行|中行|交行|邮储银行))(.*)$", part)
                if bank and bank.group(2):
                    companies.append(bank.group(1))
                    branches.append(trim_branch_role(bank.group(2)))
                else:
                    companies.append(prefix)
                    branches.append(trim_branch_role(part[bmatch.start():]))
            else:
                companies.append(part)
    return "、".join(dict.fromkeys(companies)), "、".join(dict.fromkeys(branches))


